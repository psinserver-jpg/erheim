/** 무작위 닉네임. rng 는 0 이상 1 미만을 돌려주는 함수(생략하면 Math.random). */
export function randomName(rng) {
  const r = typeof rng === 'function' ? rng() : Math.random();
  return BOT_NAMES[Math.min(BOT_NAMES.length - 1, Math.floor(r * BOT_NAMES.length))];
}

/** 문파를 여러 형태(객체·id 문자열·이름·crest 번호)로 받아 GUILDS 항목을 돌려준다. 없으면 null. */
export function findGuild(g) {
  if (g == null || g === '') return null;
  if (typeof g === 'object') return findGuild(g.id != null ? g.id : g.name);
  if (typeof g === 'number') return GUILDS[g] || null;
  for (let i = 0; i < GUILDS.length; i++) {
    if (GUILDS[i].id === g || GUILDS[i].name === g) return GUILDS[i];
  }
  return null;
}

/** 문파 이름 문자열(없으면 ''). 목록에 없는 문자열은 그대로 돌려준다. */
export function guildName(g) {
  const f = findGuild(g);
  if (f) return f.name;
  if (typeof g === 'string') return g;
  if (g && typeof g === 'object' && typeof g.name === 'string') return g.name;
  return '';
}

/** 겹치지 않는 닉네임 n 개(봇 명단 만들 때). n 이 전체보다 크면 전체를 섞어 돌려준다. */
export function pickNames(n, rng) {
  const r = typeof rng === 'function' ? rng : Math.random;
  const a = BOT_NAMES.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(r() * (i + 1));
    const t = a[i]; a[i] = a[j]; a[j] = t;
  }
  return a.slice(0, Math.max(0, Math.min(n, a.length)));
}
