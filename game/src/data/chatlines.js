/** 문구 총 개수(데이터 점검용). 주고받기는 줄 수로 센다. */
export function countLines() {
  let n = 0;
  for (const g of [LINES, REACT, SELF, SYSTEM]) for (const k in g) n += g[k].length;
  for (const ex of EXCHANGES) n += ex.lines.length;
  return n;
}
